package com.yupi.yuaiagent.agent.model;

/**
 * AgentState — 智能体状态枚举
 *
 * ═══════════════════════════════════════════════════════
 * 【为什么需要状态机？】
 * ═══════════════════════════════════════════════════════
 *
 *   Agent 是多步骤执行流程，随时需要知道它处于哪个阶段：
 *     - 空闲，可以接受新任务？
 *     - 正在执行任务中，拒绝新任务？
 *     - 已完成，结果可以取走？
 *     - 出错了，需要重置？
 *
 *   有了状态机（State Machine）：
 *     1. 防止并发混乱：RUNNING 时拒绝新的 run() 调用
 *     2. 异常可追踪：出错时转 ERROR，调用方知道发生了什么
 *     3. 生命周期清晰：每个阶段职责明确
 *
 * ═══════════════════════════════════════════════════════
 * 【状态转换图】
 * ═══════════════════════════════════════════════════════
 *
 *   ┌────────┐  run()  ┌─────────┐  正常完成/达到maxSteps  ┌──────────┐
 *   │  IDLE  │ ──────► │ RUNNING │ ─────────────────────► │ FINISHED │
 *   └────────┘         └─────────┘                        └──────────┘
 *                           │
 *                           │ 发生未捕获异常
 *                           ▼
 *                       ┌───────┐
 *                       │ ERROR │
 *                       └───────┘
 *
 *   初始状态：IDLE（BaseAgent 第35行默认值）
 *   run() 调用时：IDLE → RUNNING（若不是 IDLE 则抛 AgentException）
 *   正常结束：RUNNING → FINISHED（AI 调 terminate 工具，或达到 maxSteps）
 *   异常中断：RUNNING → ERROR（catch 块里设置）
 *
 * ═══════════════════════════════════════════════════════
 * 【为什么用枚举而不是字符串？】
 * ═══════════════════════════════════════════════════════
 *
 *   // ❌ 字符串：拼错了编译不报错，线上才崩溃
 *   if (state.equals("runing")) { ... }  // "runing" 拼错，永远不相等，难找
 *
 *   // ✅ 枚举：拼错了编译直接报错，当场发现
 *   if (state == AgentState.RUNNING) { ... }  // 拼错 RUNING → 编译失败
 */
public enum AgentState {

    /**
     * 空闲：初始状态，等待接受新任务。
     * run() 方法仅在此状态下可以被调用。
     */
    IDLE,

    /**
     * 运行中：Agent Loop 正在执行，处理当前任务。
     * 此状态下再次调用 run() 会抛出 AgentException。
     */
    RUNNING,

    /**
     * 已完成：任务执行结束（正常完成 或 达到 maxSteps 强制停止）。
     * run() 方法已返回结果，调用方可以取走。
     */
    FINISHED,

    /**
     * 错误：执行中发生未预期的异常，被 catch 块捕获后设置。
     * 与 FINISHED 的区别：FINISHED 是预期内的结束，ERROR 是意外中断。
     */
    ERROR
}
