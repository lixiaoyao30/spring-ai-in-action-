package com.yupi.yuaiagent.rag;

import org.springframework.ai.document.Document;
import org.springframework.ai.transformer.splitter.TokenTextSplitter;
import org.springframework.stereotype.Component;

import java.util.List;

/**
 * 文档切割器 —— 把长文本切成小块，方便 AI 精准检索
 *
 * ═══════════════════════════════════════════════════════════
 * 先理解"为什么要切"，用超市类比：
 *
 *   你想找"有机苹果"
 *   ❌ 没切的情况：整个超市是一个大房间，所有商品堆在一起
 *      → AI 要扫描全部内容才能找到苹果，而且找到的是整堆货
 *   ✅ 切完的情况：超市分了货架，每格只放一类商品
 *      → AI 直接去水果区第3格，精准拿到苹果
 * ═══════════════════════════════════════════════════════════
 *
 * 本项目经历【两次切割】，下面用真实文档内容演示：
 *
 * ───────────────────────────────────────────────────────────
 * 【原始文件】单身篇.md 的原始内容（5个问答连在一起）：
 *
 *   #### 如何提升自身魅力？
 *   提升自身魅力需从多方面入手。外在形象上，保持良好的个人卫生，
 *   选择适合自己身材与风格的着装，定期锻炼...推荐课程：《单身魅力》
 *
 *   #### 怎样在社交场合结识异性？
 *   在社交场合，首先要保持微笑，展现亲和力...推荐课程：《社交秘籍》
 *
 *   #### 线上交友有哪些注意事项？
 *   线上交友时，务必完善真实且有吸引力的个人资料...
 *
 *   #### 如何克服单身焦虑？
 *   正视自己的焦虑情绪，分析焦虑产生原因...
 *
 *   #### 如何判断相亲对象是否值得发展？
 *   观察相亲对象的言行举止，是否尊重他人...
 *
 *   ↑ 5个问答全挤在一起，整个文件是一个大块
 *
 * ───────────────────────────────────────────────────────────
 * 【第1次切割】LoveAppDocumentLoader 按 #### 标题切
 *
 *   切割依据：看到 #### 就切一刀
 *   切完结果：5个问答 → 5个 Document，每个只含一问一答
 *
 *   Document1 内容：
 *     "如何提升自身魅力？提升自身魅力需从多方面入手。外在形象上，
 *      保持良好的个人卫生，选择适合自己身材与风格的着装，定期锻炼
 *      塑造健康体魄。内在修养方面，培养广泛兴趣爱好，如阅读提升知
 *      识储备...推荐课程：《单身魅力提升全攻略》..."
 *      ↑ 约350字，大约500个Token
 *
 *   Document2 内容：
 *     "怎样在社交场合结识异性？在社交场合，首先要保持微笑..."
 *      ↑ 约300字
 *
 *   Document3、4、5...（同理）
 *
 *   结果：3个文件 × 5个问答 = 共15个 Document
 *
 * ───────────────────────────────────────────────────────────
 * 【第2次切割】本类 MyTokenTextSplitter 按 Token 数量切（chunkSize=200）
 *
 *   切割依据：每块超过200个Token就再切一刀
 *   切割对象：上面15个 Document
 *
 *   Document1（500Token，超过200）→ 被切成2~3小块：
 *
 *     块1a（约200Token）：
 *       "外在形象上，保持良好的个人卫生，选择适合自己身材与风格的
 *        着装，定期锻炼塑造健康体魄。内在修养方面，培养广泛兴趣爱好"
 *        ↑ 纯讲"形象+修养"
 *
 *     块1b（约200Token）：
 *       "积极参加社交活动，锻炼沟通与表达能力，以自信热情的态度展
 *        现自我。比如小李通过学习穿搭参与户外运动，逐渐变得开朗自信"
 *        ↑ 纯讲"社交+案例"
 *
 *     块1c（剩余）：
 *       "推荐课程：《单身魅力提升全攻略》该课程从形象打造..."
 *        ↑ 推荐课程广告
 *
 *   Document2~15 同理，不超过200Token的直接保留不切
 *
 *   最终结果：15个 Document → 约30~40个更小的块
 *
 * ───────────────────────────────────────────────────────────
 * 【为什么要切两次？直接第1次切成小块不行吗？】
 *
 *   第1次（按标题切）= 先保证"语义完整"，一问一答不混在一起
 *   第2次（按Token切）= 再保证"块不太长"，向量语义纯粹、检索精准
 *
 *   如果只做第1次：
 *     Document1 有500Token，向量 = 形象+修养+社交+广告 全混在一起
 *     用户问"穿搭建议" → 找到Document1 → 回答里也包含了社交和广告内容 → 不精准
 *
 *   两次都做：
 *     用户问"穿搭建议" → 精准命中块1a（纯讲形象穿搭）→ 回答更聚焦
 *
 * ───────────────────────────────────────────────────────────
 * 【对本项目是否多此一举？】
 *
 *   老实说：本项目文档很短，切不切差别不大，不切也能正常运行。
 *   但保留这一步是好习惯：文档一旦变长，不改代码就能自动处理。
 */
@Component
public class MyTokenTextSplitter {

    // 默认切割：每块最大800Token，适合普通文档（本项目文档短，基本不会触发切割）
    public List<Document> splitDocuments(List<Document> documents) {
        TokenTextSplitter splitter = new TokenTextSplitter();
        return splitter.apply(documents);
    }

    // 精细切割：每块最大200Token，块更小，向量语义更纯，检索更精准
    public List<Document> splitCustomized(List<Document> documents) {
        TokenTextSplitter splitter = new TokenTextSplitter(
                200,   // chunkSize：每块最大200Token（约中文100字）
                100,   // minChunkSizeChars：块最少100字，太短的直接丢弃（避免"的""了"这种碎片）
                10,    // minChunkLengthToEmbed：低于10字的块不做向量化
                5000,  // maxNumChunks：最多切5000块（防止超大文档耗尽内存）
                true   // keepSeparator：保留分隔符，块与块之间上下文不断裂
        );
        return splitter.apply(documents);
    }
}
